#!/usr/bin/env python3
"""Split the Yozai font into small woff2 slices covering only the glyphs used on this site.

The full Yozai-Regular.ttf (SIL OFL 1.1) is ~13 MB and the book notes use thousands of
distinct characters, so instead of one subset we emit slices with `unicode-range`
(the same trick Google Fonts uses): the browser only downloads the slices a page needs.
Characters of the UI and the book list come first so the bookshelf needs few slices;
the rest are ordered by frequency.

Outputs src/generated/fonts.css and src/generated/fonts/yozai-<n>.woff2.
Runs after `npm run data` (it reads the generated book data). Requires: pip install fonttools brotli
"""

import collections
import pathlib
import shutil
import urllib.request

from fontTools import subset
from fontTools.ttLib import TTFont

SITE = pathlib.Path(__file__).resolve().parent.parent
FONT_URL = "https://shen-shanshan.github.io/font/Yozai-Regular.ttf"
SOURCE_FONT = SITE / ".font-cache" / "Yozai-Regular.ttf"
OUT_DIR = SITE / "src" / "generated" / "fonts"
OUT_CSS = SITE / "src" / "generated" / "fonts.css"
SLICE_SIZE = 150

PRIMARY_SOURCES = [
    SITE / "index.html",
    *sorted((SITE / "src").rglob("*.vue")),
    *sorted((SITE / "src").rglob("*.ts")),
    SITE / "src" / "generated" / "books.json",
]
CONTENT_SOURCES = sorted((SITE / "public" / "data").glob("*.json"))


def read(paths) -> str:
    return "".join(p.read_text(encoding="utf-8") for p in paths)


def ordered_chars(supported: set[int]) -> list[str]:
    primary = {chr(c) for c in range(0x20, 0x7F)}
    primary.update("，。、；：？！“”‘’（）《》【】—…·")
    primary.update(read(PRIMARY_SOURCES))
    counts = collections.Counter(read(CONTENT_SOURCES))

    def keep(c: str) -> bool:
        return c.isprintable() and ord(c) in supported

    head = sorted((c for c in primary if keep(c)), key=lambda c: -counts[c])
    rest = [c for c, _ in counts.most_common() if keep(c) and c not in primary]
    return head + rest


def unicode_range(chars: str) -> str:
    return ", ".join(f"U+{ord(c):X}" for c in sorted(chars))


def main() -> None:
    if not SOURCE_FONT.exists():
        SOURCE_FONT.parent.mkdir(parents=True, exist_ok=True)
        print(f"Downloading {FONT_URL} ...")
        urllib.request.urlretrieve(FONT_URL, SOURCE_FONT)

    supported = set(TTFont(SOURCE_FONT).getBestCmap())
    chars = ordered_chars(supported)

    shutil.rmtree(OUT_DIR, ignore_errors=True)
    OUT_DIR.mkdir(parents=True)
    css = ["/* Generated by scripts/subset-font.py: Yozai (悠哉字体, SIL OFL 1.1) sliced by unicode-range. */"]
    total = 0
    for i in range(0, len(chars), SLICE_SIZE):
        text = "".join(chars[i:i + SLICE_SIZE])
        out = OUT_DIR / f"yozai-{i // SLICE_SIZE}.woff2"
        subset.main([
            str(SOURCE_FONT),
            f"--text={text}",
            f"--output-file={out}",
            "--flavor=woff2",
            "--layout-features=*",
            "--no-hinting",
        ])
        total += out.stat().st_size
        css.append(
            "@font-face {\n"
            "\tfont-family: 'Yozai';\n"
            f"\tsrc: url('./fonts/{out.name}') format('woff2');\n"
            "\tfont-display: swap;\n"
            f"\tunicode-range: {unicode_range(text)};\n"
            "}"
        )
    OUT_CSS.write_text("\n".join(css) + "\n", encoding="utf-8")
    print(f"{len(chars)} characters -> {len(css) - 1} slices in {OUT_DIR.relative_to(SITE)} ({total // 1024} KB total)")


if __name__ == "__main__":
    main()
